/** A 5x8 bitmap font, drawn in code. Each number is a row of 5 bits; row 8 holds descenders. */
export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 8;
export const LINE_HEIGHT = 10;
const GAP = 1;
const SPACE_WIDTH = 3;

const rows = (...values: number[]): number[] => {
  const out = [...values];
  while (out.length < GLYPH_HEIGHT) out.push(0);
  return out;
};

