/** Which columns a letter really uses, so an i doesn't take up as much room as an M. Digits stay even, to line up in counters. */
function shapeOf(char: string): { left: number; width: number } {
  if (char === " ") return { left: 0, width: SPACE_WIDTH };
  if (char >= "0" && char <= "9") return { left: 0, width: GLYPH_WIDTH };
  const used = (GLYPHS[char] ?? GLYPHS["?"]).reduce((all, row) => all | row, 0);
  let left = 0;
  while (left < GLYPH_WIDTH - 1 && !(used & (1 << (GLYPH_WIDTH - 1 - left)))) left++;
  let right = GLYPH_WIDTH - 1;
  while (right > left && !(used & (1 << (GLYPH_WIDTH - 1 - right)))) right--;
  return { left, width: right - left + 1 };
}

const SHAPES = new Map<string, { left: number; width: number }>();
function shape(char: string): { left: number; width: number } {
  let found = SHAPES.get(char);
  if (!found) SHAPES.set(char, (found = shapeOf(char)));
  return found;
}

export function measureText(text: string): number {
  let width = 0;
  for (const char of text) width += shape(char).width + GAP;
  return Math.max(0, width - GAP);
}

export function wrapText(text: string, maxWidth: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const raw of text.split(" ")) {
    let word = raw;
    while (measureText(word) > maxWidth) {
      if (line) {
        lines.push(line);
        line = "";
      }
      let fits = 1;
      while (fits < word.length && measureText(word.slice(0, fits + 1)) <= maxWidth) fits++;
      lines.push(word.slice(0, fits));
      word = word.slice(fits);
    }
    const candidate = line ? `${line} ${word}` : word;
    if (measureText(candidate) > maxWidth) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color;
  let px = Math.round(x);
  const py = Math.round(y);
  for (const char of text) {
    const glyph = GLYPHS[char] ?? GLYPHS["?"];
    const { left, width } = shape(char);
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      const bits = glyph[row];
      if (!bits) continue;
      for (let col = left; col < left + width; col++) {
        if (bits & (1 << (GLYPH_WIDTH - 1 - col))) ctx.fillRect(px + (col - left) * scale, py + row * scale, scale, scale);
      }
    }
    px += (width + GAP) * scale;
  }
}

export function drawTextCentered(ctx: CanvasRenderingContext2D, text: string, centerX: number, y: number, color: string): void {
  drawText(ctx, text, centerX - measureText(text) / 2, y, color);
}

/** A line of interface text pinned to a spot in the world: centered over `x`, sitting on `y`. */
export function drawLabelAt(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  const at = guiPoint(ctx, x, y);
  onGui(ctx, () => drawText(ctx, text, at.x - (measureText(text) * scale) / 2, at.y - (GLYPH_HEIGHT - 1) * scale, color, scale));
}
